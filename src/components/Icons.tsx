/** Eight-spoke ornament used throughout the brand as a small flourish. */
export function AsteriskIcon({
  spokes = 4,
  strokeWidth = 2.4,
  ...props
}: IconProps & { spokes?: number }) {
  const angles = Array.from({ length: spokes }, (_, i) => (180 / spokes) * i);
  return (
    <Svg strokeWidth={strokeWidth} {...props}>
      {angles.map((angle) => (
        <line
          key={angle}
          x1="12"
          y1="2.5"
          x2="12"
          y2="21.5"
          transform={`rotate(${angle} 12 12)`}
        />
      ))}
    </Svg>
  );
}
